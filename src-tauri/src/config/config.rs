use super::{IClashTemp, IProfiles, IRuntime, IVerge};
use crate::utils::{dirs, help};
use anyhow::{anyhow, Result};
use once_cell::sync::OnceCell;
use parking_lot::RwLock;
use std::path::PathBuf;
use std::sync::Arc;

pub const RUNTIME_CONFIG: &str = "clash-astra.yaml";
pub const CHECK_CONFIG: &str = "clash-astra-check.yaml";

#[derive(Clone, Debug)]
pub struct ConfigSnapshot {
    pub revision: u64,
    pub runtime_revision: u64,
    pub profile_versions: std::collections::BTreeMap<String, u64>,
    pub clash: IClashTemp,
    pub verge: IVerge,
    pub profiles: IProfiles,
    pub runtime: IRuntime,
}

impl ConfigSnapshot {
    pub fn write_runtime(&self, typ: ConfigType) -> Result<PathBuf> {
        let path = match typ {
            ConfigType::Run => dirs::app_home_dir()?.join(RUNTIME_CONFIG),
            ConfigType::Check => dirs::app_temp_dir()?.join(CHECK_CONFIG),
        };

        let config = self
            .runtime
            .config
            .as_ref()
            .ok_or(anyhow!("failed to get runtime config"))?;

        help::save_yaml(&path, &config, Some("# Generated by Clash Astra"))?;
        Ok(path)
    }
}

/// 读取方持有不可变快照；仅应用层协调器能够发布新版本。
pub struct Config;

impl Config {
    fn state() -> &'static RwLock<Arc<ConfigSnapshot>> {
        static STATE: OnceCell<RwLock<Arc<ConfigSnapshot>>> = OnceCell::new();
        STATE.get_or_init(|| {
            RwLock::new(Arc::new(ConfigSnapshot {
                revision: 0,
                runtime_revision: 0,
                profile_versions: Default::default(),
                clash: IClashTemp::new(),
                verge: IVerge::new(),
                profiles: crate::infrastructure::profile_catalog::load(),
                runtime: IRuntime::new(),
            }))
        })
    }

    pub fn snapshot() -> Arc<ConfigSnapshot> {
        Self::state().read().clone()
    }
    pub fn clash() -> IClashTemp {
        Self::snapshot().clash.clone()
    }
    pub fn verge() -> IVerge {
        Self::snapshot().verge.clone()
    }
    pub fn profiles() -> IProfiles {
        Self::snapshot().profiles.clone()
    }
    pub fn runtime() -> IRuntime {
        Self::snapshot().runtime.clone()
    }

    pub(crate) fn publish(mut next: ConfigSnapshot) -> u64 {
        let mut state = Self::state().write();
        next.revision = state.revision + 1;
        next.runtime_revision = next
            .runtime_revision
            .max(state.runtime_revision + u64::from(next.runtime.config != state.runtime.config));
        let revision = next.revision;
        *state = Arc::new(next);
        revision
    }
}

#[derive(Debug)]
pub enum ConfigType {
    Run,
    Check,
}
